
class Celda:

    def __init__(self, costo_base, muro=False, salida=False):
        self.costo_base = costo_base
        self.muro = muro
        self.salida = salida
        self.fuego = False
        self.agentes = []

    # el costo de la celda depende de la cantidad de agentes en ella, se utiliza
    # una funcion lineal
    @property
    def costo(self):
        return self.costo_base + 2 * len(self.agentes)


